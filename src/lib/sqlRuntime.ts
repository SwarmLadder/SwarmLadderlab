// SQL executes locally in the existing Pyodide Worker using Python's sqlite3.
// The builder computes reference digests, never publishes reference SQL text.
export type SqlGrade = { base: string; edge: string };
export type SqlMode = "run" | "grade";

export function sqlProgram(sql: string, mode: SqlMode, grade?: SqlGrade, challenge = "", schemaTask = ""): string {
  const payload = JSON.stringify({ sql, mode, grade: grade ?? null, challenge, schemaTask });
  // A JSON string literal is also a Python string literal. Decode it inside
  // Python rather than interpolating user-submitted SQL as executable Python.
  const literal = JSON.stringify(payload);
  return [
    "import sqlite3, json, hashlib, pathlib, re",
    "cfg = json.loads(" + literal + ")",
    "sql_text = cfg['sql']",
    "if len(sql_text) > 40000: raise ValueError('Maximum SQL length is 40,000 characters')",
    "",
    "def new_sql_connection(variant):",
    "    db = sqlite3.connect(':memory:')",
    "    dump = pathlib.Path('/course/sql/fixtures/' + variant + '.sql').read_text(encoding='utf-8')",
    "    db.executescript(dump)",
    "    calls = [0]",
    "    def limit():",
    "        calls[0] += 1",
    "        return 1 if calls[0] > 1000 else 0",
    "    db.set_progress_handler(limit, 1000)",
    "    return db",
    "",
    "def check_query():",
    "    trimmed = re.sub(r'(?m)^\\s*--[^\\n]*(?:\\n|$)', '', sql_text).strip()",
    "    if not re.match(r'(?is)^(SELECT|WITH)\\b', trimmed):",
    "        raise ValueError('Submit a read-only SELECT or WITH ... SELECT query')",
    "    if not sqlite3.complete_statement(sql_text):",
    "        raise ValueError('End your query with a semicolon')",
    "    for variant in ('base', 'edge'):",
    "        db = new_sql_connection(variant)",
    "        try:",
    "            db.execute('PRAGMA query_only=ON')",
    "            cursor = db.execute(sql_text)",
    "            if cursor.description is None:",
    "                raise ValueError('Your SQL must return rows')",
    "            rows = cursor.fetchmany(2001)",
    "            if len(rows) > 2000: raise ValueError('Limit results to 2,000 rows')",
    "            rows = tuple(tuple(round(v, 7) if isinstance(v, float) else v for v in row) for row in rows)",
    "            actual = hashlib.sha256(json.dumps(rows, ensure_ascii=False, separators=(',', ':')).encode('utf-8')).hexdigest()",
    "            if actual != cfg['grade'][variant]:",
    "                print('❌ ' + variant + ' dataset mismatch. Check columns, ordering, NULLs and edge cases.')",
    "                return",
    "        finally:",
    "            db.close()",
    "    print('✅ SQL challenge ' + cfg['challenge'] + ': passed both datasets')",
    "",
    "def run_script():",
    "    db = new_sql_connection('base')",
    "    try:",
    "        buffer = ''",
    "        count = 0",
    "        for line in sql_text.splitlines(keepends=True):",
    "            buffer += line",
    "            if not sqlite3.complete_statement(buffer): continue",
    "            stmt, buffer = buffer, ''",
    "            if not re.sub(r'(?m)^\\s*--[^\\n]*(?:\\n|$)', '', stmt).strip(): continue",
    "            count += 1",
    "            if count > 50: raise ValueError('Maximum 50 statements per run')",
    "            cur = db.execute(stmt)",
    "            print('Statement ' + str(count))",
    "            if cur.description:",
    "                print(' | '.join(c[0] for c in cur.description))",
    "                rows = cur.fetchmany(31)",
    "                for row in rows[:30]:",
    "                    print(' | '.join('NULL' if v is None else str(v) for v in row))",
    "                if len(rows) > 30: print('…more results (showing first 30 rows)')",
    "            else:",
    "                print('Rows changed: ' + str(max(0, cur.rowcount)))",
    "        if re.sub(r'(?m)^\\s*--[^\\n]*(?:\\n|$)', '', buffer).strip():",
    "            raise ValueError('Incomplete SQL; terminate each statement with a semicolon')",
    "        if not count: print('Add a SQL statement to run.')",
    "    finally:",
    "        db.close()",
    "",
    "def check_schema():",
    "    import sys",
    "    sys.path.insert(0, '/course/sql/tools')",
    "    from schema_practice import check",
    "    ok, message = check(cfg['schemaTask'], sql_text)",
    "    if ok: print('✅ SQL challenge ' + cfg['challenge'] + ': passed schema tests')",
    "    else: print('❌ ' + message)",
    "",
    "if cfg['mode'] == 'grade':",
    "    check_schema() if cfg.get('schemaTask') else check_query()",
    "else: run_script()",
  ].join("\n");
}
